// Minimal bundler: wraps src modules into one CommonJS main.js for Obsidian.
"use strict";
const fs = require("fs"), path = require("path");
const mods = ["model", "views", "main"];
let out = `/* dotpm Companion — generated by build.js, do not edit. Source: src/ */\n"use strict";\n`;
out += `const __mods = {}; const __cache = {};\n`;
out += `function __req(n){ if(n in __cache) return __cache[n].exports; if(!(n in __mods)) return require(n); const m={exports:{}}; __cache[n]=m; __mods[n](m, m.exports, __req); return m.exports; }\n`;
for (const m of mods) {
  const src = fs.readFileSync(path.join(__dirname, "src", m + ".js"), "utf8").replace(/^"use strict";\n/, "");
  out += `__mods["./${m}"] = function(module, exports, require){\n${src}\n};\n`;
}
out += `module.exports = __req("./main");\n`;
fs.writeFileSync(path.join(__dirname, "main.js"), out);
console.log("main.js", (out.length / 1024).toFixed(1) + " KB");
